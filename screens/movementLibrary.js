// ─── HELPERS ─────────────────────────────────────────────────────────────────

// Get exercises for a pattern filtered by available equipment
export function getExercisesForEquipment(patternKey, availableEquipment) {
  const pattern = MOVEMENT_PATTERNS[patternKey];
  if (!pattern) return [];
  return pattern.exercises.filter(ex =>
    ex.equipment.every(eq => availableEquipment.includes(eq)) ||
    ex.equipment.includes('bodyweight')
  );
}

// Get the best (primary) exercise for a pattern given equipment
export function getBestExercise(patternKey, availableEquipment) {
  const exercises = getExercisesForEquipment(patternKey, availableEquipment);
  return exercises.find(ex => ex.primary_alternative) || exercises[0] || null;
}

// Equipment that supports proper external loading. When a user has any of
// these, bodyweight-only rotation fillers (e.g. push-up variations) shouldn't
// be programmed as main exercises — they can't be progressively overloaded
// the way loaded movements can.
const LOADED_EQUIPMENT = ['barbell', 'dumbbells', 'cables', 'machines', 'smith', 'kettlebells'];

// Get all exercises for a pattern. primary_alternative: true exercises come first,
// then the rotation pool in the order they appear in the library.
export function getAllExercisesForPattern(patternKey, availableEquipment) {
  let pool = getExercisesForEquipment(patternKey, availableEquipment);

  // Gym users: drop bodyweight-only exercises from the selection pool unless
  // they're a deliberate primary pick (Nordic curl, plank) or removing them
  // would leave the pattern too thin to rotate through.
  const hasLoadedGym = (availableEquipment || []).some(eq => LOADED_EQUIPMENT.includes(eq));
  if (hasLoadedGym) {
    const filtered = pool.filter(ex =>
      ex.primary_alternative ||
      !(ex.equipment.length === 1 && ex.equipment[0] === 'bodyweight')
    );
    if (filtered.length >= 2) pool = filtered;
  }

  return pool.sort((a, b) => (a.primary_alternative ? 0 : 1) - (b.primary_alternative ? 0 : 1));
}

// Get rotation alternatives for an exercise (same pattern, different exercise)
export function getAlternatives(patternKey, currentExerciseId, availableEquipment) {
  return getExercisesForEquipment(patternKey, availableEquipment)
    .filter(ex => ex.id !== currentExerciseId);
}

// Get all movement pattern keys
export const PATTERN_KEYS = Object.keys(MOVEMENT_PATTERNS);

// Exercise name → the label of the pattern it belongs to. Built once from the
// library itself, so it can never drift from the AVAILABLE EXERCISES grouping
// the coach is shown.
const _PATTERN_LABEL_BY_NAME = (() => {
  const map = {};
  Object.values(MOVEMENT_PATTERNS).forEach(pat => {
    pat.exercises.forEach(ex => { map[ex.name.toLowerCase()] = pat.label; });
  });
  return map;
})();

// The movement-pattern label for an exercise name, or null for a name that
// isn't in the library (a renamed or hand-entered slot).
//
// The coach's program context used to tag each slot with muscles instead, but
// normaliseMuscle collapses 'lower chest' and 'upper chest' into plain 'chest',
// so a decline press and a flat bench arrived at the model as the identical
// tag [chest/triceps] — and it duly offered flat-bench "alternatives" for a
// lower-chest slot. The pattern label is the grouping the exercise menu already
// uses, so it names the group a replacement has to come from.
export function getPatternLabelForExercise(name) {
  return _PATTERN_LABEL_BY_NAME[name?.toLowerCase()] || null;
}

// Slot map — used by program generator to assign exercises to training slots
export const SLOT_PATTERNS = PATTERN_KEYS.reduce((acc, key) => {
  const slot = MOVEMENT_PATTERNS[key].slot;
  if (slot) {
    if (!acc[slot]) acc[slot] = [];
    acc[slot].push(key);
  }
  return acc;
}, {});
