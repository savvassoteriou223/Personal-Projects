// Get exercises for a pattern filtered by available equipment
export function getExercisesForEquipment(patternKey, availableEquipment) {
  const pattern = MOVEMENT_PATTERNS[patternKey];
  if (!pattern) return [];

  return pattern.exercises.filter(ex =>
    ex.equipment.every(eq => availableEquipment.includes(eq)) ||
    ex.equipment.includes('bodyweight')
  );
}

// Get the best exercise for a pattern given equipment
export function getBestExercise(patternKey, availableEquipment) {
  const options = getExercisesForEquipment(patternKey, availableEquipment);
  return options[0] || null;
}

// Get all patterns
export function getAllPatterns() {
  return Object.keys(MOVEMENT_PATTERNS);
}

// Get equipment warning for bodyweight-only users
export function getEquipmentWarnings(availableEquipment) {
  const warnings = [];

  if (availableEquipment.includes('Bodyweight only') && availableEquipment.length === 1) {
    warnings.push({
      level: 'high',
      message: 'Bodyweight training will produce results initially but you will plateau without progressive overload. A weighted vest (~€30) extends progress significantly.',
      source: 'Van Every, Nippard & Phillips (2025): mechanical tension via progressive overload is the primary driver of hypertrophy.',
    });
  }

  if (!availableEquipment.includes('pullup_bar') && !availableEquipment.includes('cables') && !availableEquipment.includes('machines')) {
    warnings.push({
      level: 'medium',
      message: 'Pull-ups and lat pulldowns are among the most effective back exercises. A doorframe pull-up bar (~€20) is one of the best investments you can make.',
      source: null,
    });
  }

  return warnings;
}